/**
 * 外接保存适配器 —— **占位，未实现**。
 *
 * 这是为「数据不只存在本机」预留的位置：用户自建的服务器、对象存储，
 * 或将来某个第三方同步服务，都可以在这里接上，而不必改动仓储层与页面。
 *
 * 之所以现在就写这个文件而不是等要做时再建：仓储层只依赖下面这份接口契约。
 * 契约先定下来，将来接线时就是「补一个实现」，而不是回头重构调用方。
 *
 * ---------------------------------------------------------------------------
 * 实现时必须满足的契约
 * ---------------------------------------------------------------------------
 *
 * 1. **方法签名与 `StorageAdapter` 完全一致**（get / set / del / keys / clear /
 *    bulkSet）。仓储层不感知后端是谁，换了实现业务逻辑一行都不用改。
 *
 * 2. **`keys()` 只返回本应用自己的键**（`tc:v1:` 前缀）。外接端可能同时存着
 *    别的数据，全量返回会让「清空 / 导出」误伤无关内容。
 *
 * 3. **必须抵御并发写**。本机与远端可能同时修改同一份数据。参考方向：
 *    给每个键带一个修订号（revision）或 updatedAt，写入时做乐观锁校验，
 *    冲突则抛错交由上层合并——**切勿静默覆盖**，那会直接吃掉用户数据。
 *
 * 4. **失败必须抛错，不得静默降级**。如果写远端失败却当作成功返回，
 *    用户会以为数据已备份，实际上只存在于一个随时会被清掉的浏览器里。
 *
 * 5. **密钥不得硬编码**。接入凭据应由用户在自己的设置里填写并存在本机，
 *    随仓库分发的代码里不能出现任何 token。
 *
 * ---------------------------------------------------------------------------
 * 接入时需要同步改动的地方
 * ---------------------------------------------------------------------------
 *
 * - `src/storage/index.js` 的 `getAdapter()`：增加一个「已配置外接端」的分支。
 * - 设置页：新增外接端的地址与凭据表单，以及「同步 / 断开」入口。
 * - 导入导出（M2）：备份文件里要能标注数据来源，避免把远端数据导回本机时产生重复。
 *
 * 在此之前，本文件不导出任何可用实现。
 */

/** 未实现时统一抛出的错误类型，便于上层区分「没配」与「配了但坏了」。 */
export class RemoteAdapterNotImplementedError extends Error {
  constructor(message = '外接保存尚未实现，当前数据只保存在本机浏览器中') {
    super(message)
    this.name = 'RemoteAdapterNotImplementedError'
  }
}

